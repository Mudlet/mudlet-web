#!/usr/bin/env node
/**
 * Regenerate src/mud/protocol/qtCodePages.generated.ts — the upper halves of
 * the single-byte encodings desktop Mudlet decodes through Qt rather than
 * through its own TEncodingTable (codePages.ts carries those).
 *
 * The browser has decoders for every one of these, but they are WHATWG's, and
 * WHATWG decodes for web compatibility rather than to the standard: ISO 8859-1
 * and 8859-9 are read as Windows-1252/1254, ISO 8859-11 as Windows-874, a
 * byte Windows-125x leaves unassigned comes out as a C1 control, and ISO
 * 8859-7/8 follow newer table revisions. Desktop reads Qt's tables, which give
 * U+FFFD for an unassigned byte. Node does not even agree with the browser
 * (its TextDecoder is ICU's), so the tables are carried rather than asked for.
 *
 * Sources:
 *  - Qt's `qsimplecodec.cpp` (qt5compat, `--qt-ref`) for the ISO 8859 pages it
 *    carries, KOI8-R and WINDOWS-1250…1258;
 *  - ISO 8859-1 and 8859-15, which Qt implements in code (QLatin1Codec,
 *    QLatin15Codec) rather than as a table: the standard, C1 controls and all;
 *  - ISO 8859-11, which desktop reads as plain TIS-620 — nothing at 0x80–0xA0,
 *    not even the Windows-874 euro sign and quotes Qt's own table adds.
 *
 *   node scripts/generate-qt-code-pages.mjs
 *   node scripts/generate-qt-code-pages.mjs --qt-ref v6.11.1
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(HERE, '../src/mud/protocol/qtCodePages.generated.ts');

const args = process.argv.slice(2);
const opt = (name, fallback) => {
    const i = args.indexOf(name);
    return i >= 0 ? args[i + 1] : fallback;
};
const QT_REF = opt('--qt-ref', 'v6.11.1');
const QT_URL = `https://raw.githubusercontent.com/qt/qt5compat/${QT_REF}/src/core5/codecs/qsimplecodec.cpp`;

const r = await fetch(QT_URL);
if (!r.ok) throw new Error(`${QT_URL}: HTTP ${r.status}`);
const src = await r.text();

/** Qt name → its 128 upper-half code points. */
const qt = {};
const entry = /\{\s*"([^"]+)",\s*\{[^}]*\},\s*-?\d+,\s*(?:\/\/[^\n]*)?\s*\{?([^}]*)\}/g;
for (const m of src.matchAll(entry)) {
    const values = [...m[2].replace(/\/\*.*?\*\//g, '').matchAll(/0x([0-9A-Fa-f]{4})/g)].map(v => parseInt(v[1], 16));
    if (values.length === 128) qt[m[1]] = values;
}

const pick = (name) => {
    const t = qt[name];
    if (!t) throw new Error(`qsimplecodec.cpp has no 128-entry table for ${name}`);
    return [...t];
};

const latin1 = Array.from({ length: 128 }, (_, i) => 0x80 + i);
const latin9 = [...latin1];
for (const [b, cp] of [[0xa4, 0x20ac], [0xa6, 0x0160], [0xa8, 0x0161], [0xb4, 0x017d],
    [0xb8, 0x017e], [0xbc, 0x0152], [0xbd, 0x0153], [0xbe, 0x0178]]) latin9[b - 0x80] = cp;
const tis620 = pick('TIS-620');
for (let b = 0x80; b <= 0xa0; b++) tis620[b - 0x80] = 0xfffd;

/** Decoder label (charset.ts's normalizeCharsetName) → table. */
const pages = {
    'iso-8859-1': latin1,
    'iso-8859-2': pick('ISO-8859-2'),
    'iso-8859-3': pick('ISO-8859-3'),
    'iso-8859-4': pick('ISO-8859-4'),
    'iso-8859-5': pick('ISO-8859-5'),
    'iso-8859-6': pick('ISO-8859-6'),
    'iso-8859-7': pick('ISO-8859-7'),
    'iso-8859-8': pick('ISO-8859-8'),
    'iso-8859-9': pick('ISO-8859-9'),
    'iso-8859-10': pick('ISO-8859-10'),
    'iso-8859-11': tis620,
    'iso-8859-13': pick('ISO-8859-13'),
    'iso-8859-14': pick('ISO-8859-14'),
    'iso-8859-15': latin9,
    'iso-8859-16': pick('ISO-8859-16'),
    'koi8-r': pick('KOI8-R'),
};
for (let n = 1250; n <= 1258; n++) pages[`windows-${n}`] = pick(`windows-${n}`);

const hex = (cp) => cp.toString(16).toUpperCase().padStart(4, '0');
let body = '';
for (const [label, table] of Object.entries(pages)) {
    body += `    '${label}':\n`;
    for (let row = 0; row < 16; row++) {
        const chunk = table.slice(row * 8, row * 8 + 8).map(hex).join('');
        const lo = (0x80 + row * 8).toString(16).toUpperCase();
        const hi = (0x80 + row * 8 + 7).toString(16).toUpperCase();
        body += `        ${row === 0 ? '' : '+ '}'${chunk}'${row === 15 ? ',' : ''} // ${lo}-${hi}\n`;
    }
}

const out = `// Generated by scripts/generate-qt-code-pages.mjs from qt5compat@${QT_REF}
// src/core5/codecs/qsimplecodec.cpp — do not edit by hand.
//
// The upper half (0x80-0xFF) of each single-byte encoding desktop Mudlet reads
// through Qt, as 128 four-digit code points, eight per line. FFFD marks a byte
// the encoding leaves unassigned. See the generator for why these are carried.

export const QT_CODE_PAGES: Readonly<Record<string, string>> = {
${body}};
`;
writeFileSync(OUT, out);
console.log(`wrote ${OUT} (${Object.keys(pages).length} pages)`);
